# Regenerates the committed *.h shader headers for test_d3dmetal_gpu_limits (#453).
# Needs Microsoft's official DXC release v1.9.2609 (dxc_2026_09_29.zip, SHA-256
# ad31b1fc8443175d204f77a611fdb3ef2ec42759bdc2f1167368de24a4a7e7f1); it has no
# macOS build, so bin/x64/dxc.exe runs under a Wine/CrossOver loader.
#
#   WINE=/path/to/wine DXC=/path/to/dxc/bin/x64/dxc.exe ./compile.sh
set -eu
: "${WINE:?set WINE to a Wine or CrossOver wine loader}"
: "${DXC:?set DXC to dxc.exe from the DXC v1.9.2609 release}"
cd "$(dirname "$0")"
dxc() { "$WINE" "$DXC" -nologo "$@"; }
dxc -T cs_6_6 -E main -Vn g_wave_lanes_cs -Fh wave_lanes.h wave_lanes.hlsl
dxc -T cs_6_6 -E main -D BX_WAVE64=1 -Vn g_wave64_lanes_cs -Fh wave64_lanes.h wave_lanes.hlsl
dxc -T cs_6_6 -E main -Vn g_atomic64_image_cs -Fh atomic64_image.h atomic64_image.hlsl
dxc -T cs_6_6 -E main -Vn g_atomic64_buffer_cs -Fh atomic64_buffer.h atomic64_buffer.hlsl
dxc -T cs_6_6 -E main -Vn g_lock64_image_cs -Fh lock64_image.h lock64_image.hlsl
# Strip CRs and prepend the licence and provenance header.
for pair in wave_lanes:wave_lanes wave64_lanes:wave_lanes atomic64_image:atomic64_image \
            atomic64_buffer:atomic64_buffer lock64_image:lock64_image; do
    h=${pair%%:*} src=${pair#*:}
    {
        printf '// SPDX-License-Identifier: GPL-3.0-or-later\n//\n'
        printf '// GENERATED by DXC 1.9.2609 from %s.hlsl by compile.sh; do not edit.\n\n' "$src"
        tr -d '\r' < "$h.h"
    } > "$h.h.tmp" && mv "$h.h.tmp" "$h.h"
done
